"""
mltunex.reporting.experiment_logger
─────────────────────────────────────
Produces four structured, professional Markdown experiment artefacts:

  1. preprocessing_report.md
  2. model_metrics.xlsx
  3. selection_report.md
  4. tuning_report.md
"""
from __future__ import annotations

import json
import os
from datetime import datetime
from typing import Any, Dict, List, Optional, Tuple

import pandas as pd

_GEN_COMMENT = "<!-- generated by MLTuneX -->"


def _doc(title: str, subtitle: str, timestamp: str, exp_name: str) -> List[str]:
    """Consistent YAML-like front-matter header used by all four reports."""
    return [
        "---",
        f"title: \"{title}\"",
        f"experiment: \"{exp_name}\"",
        f"generated: \"{timestamp}\"",
        "generator: MLTuneX AutoML Pipeline",
        "---",
        "",
        f"# {title}",
        "",
        f"> {subtitle}  ",
        f"> **Experiment:** `{exp_name}` &nbsp;·&nbsp; **Generated:** `{timestamp}`",
        "",
        "---",
        "",
    ]


def _kv_table(rows: List[Tuple[str, str]], header: Tuple[str, str] = ("Property", "Value")) -> List[str]:
    k, v = header
    lines = [f"| {k} | {v} |", "|:---|:---|"]
    lines += [f"| {r} | {c} |" for r, c in rows]
    return lines


def _df_to_md(df: pd.DataFrame, bold_col: Optional[str] = None) -> List[str]:
    if df.empty:
        return ["> *No data available.*"]
    cols   = list(df.columns)
    header = "| " + " | ".join(f"**{c}**" if c == bold_col else c for c in cols) + " |"
    sep    = "| " + " | ".join(":---" for _ in cols) + " |"
    rows   = []
    for row in df.itertuples(index=False, name=None):
        cells = [f"{v:.4f}" if isinstance(v, float) else str(v) for v in row]
        rows.append("| " + " | ".join(cells) + " |")
    return [header, sep] + rows


def _bar(value: float, width: int = 24) -> str:
    """ASCII progress bar that renders as a filled Unicode block."""
    filled = round(value * width)
    return "█" * filled + "░" * (width - filled)


class ExperimentLogger:
    """Writes all four experiment artefacts for a single MLTuneX run."""

    def __init__(self, base_log_dir: str = "logs/", experiment_name: str = "exp") -> None:
        ts = datetime.now().strftime("%Y%m%d_%H%M%S")
        self._dir      = os.path.join(base_log_dir, f"{experiment_name}_{ts}")
        self._ts       = ts
        self._ts_human = datetime.now().strftime("%d %b %Y, %H:%M:%S")
        self._name     = experiment_name
        os.makedirs(self._dir, exist_ok=True)
        print(f"[MLTuneX] Experiment artefacts -> {self._dir}")

    # ─────────────────────────────────────────────────────────────────
    # 1. Preprocessing report
    # ─────────────────────────────────────────────────────────────────

    def log_preprocessing(
        self,
        profile: Dict[str, Any],
        pipeline_steps: List[Tuple[str, Any]],
        profiling_strategy: str,
        preprocessed_train: Optional[pd.DataFrame] = None,
        preprocessed_test:  Optional[pd.DataFrame] = None,
    ) -> None:
        lines = _doc(
            "Data Preprocessing Report",
            f"Profiling strategy: **{profiling_strategy}**",
            self._ts_human, self._name,
        )

        # ── 1. Dataset snapshot ──────────────────────────────────────
        lines += ["## Dataset Snapshot", ""]
        num_rows     = profile.get("num_rows", 0)
        num_features = profile.get("num_features", 0)
        target       = profile.get("target_column", "—")
        imbalance    = profile.get("imbalance_ratio")
        num_feats    = profile.get("numeric_features", [])
        cat_feats    = profile.get("categorical_features", [])

        lines += _kv_table([
            ("Rows",              f"`{num_rows:,}`"),
            ("Features",          f"`{num_features}`"),
            ("Numeric features",  f"`{len(num_feats)}`"),
            ("Categorical features", f"`{len(cat_feats)}`"),
            ("Target column",     f"`{target}`"),
            ("Imbalance ratio",   f"`{imbalance}`" if imbalance else "_n/a (regression)_"),
            ("Profiling strategy", f"`{profiling_strategy}`"),
        ])

        # ── 2. Feature inventory ─────────────────────────────────────
        lines += ["", "### Numeric Features", ""]
        if num_feats:
            lines.append(" &nbsp; ".join(f"`{f}`" for f in num_feats))
        else:
            lines.append("_None detected._")

        lines += ["", "### Categorical Features", ""]
        if cat_feats:
            lines.append(" &nbsp; ".join(f"`{f}`" for f in cat_feats))
        else:
            lines.append("_None detected._")

        # ── 3. Target distribution ───────────────────────────────────
        target_dist = profile.get("target_distribution", {})
        if target_dist and len(target_dist) <= 20:
            lines += ["", "---", "## Target Distribution", ""]
            lines += ["| Class | Proportion | Distribution |", "|:---|---:|:---|"]
            for cls, pct in sorted(target_dist.items(), key=lambda x: x[1], reverse=True):
                lines.append(f"| `{cls}` | {pct:.2%} | {_bar(pct, 20)} |")

        # ── 4. Missing data ──────────────────────────────────────────
        missing = {k: v for k, v in profile.get("missing_counts", {}).items() if v > 0}
        lines += ["", "---", "## Missing Data", ""]
        if missing:
            pct_map = profile.get("missing_pct", {})
            lines += ["| Column | Count | Pct | Severity | Action |",
                      "|:---|---:|---:|:---:|:---|"]
            for col, count in sorted(missing.items(), key=lambda x: x[1], reverse=True):
                pct = pct_map.get(col, 0)
                sev, action = (
                    ("🔴 High",   "Consider dropping or using model-based imputation")
                    if pct > 30 else
                    ("🟡 Medium", "Impute with median / mode")
                    if pct > 5 else
                    ("🟢 Low",    "Impute with median / mode")
                )
                lines.append(f"| `{col}` | {count:,} | {pct:.1f}% | {sev} | {action} |")
        else:
            lines.append("> ✅ **No missing values detected.** Dataset is complete.")

        # ── 5. Distribution statistics ───────────────────────────────
        if "skewness" in profile:
            top_skew = sorted(
                [(k, v) for k, v in profile["skewness"].items() if v != 0],
                key=lambda x: abs(x[1]), reverse=True
            )[:12]
            if top_skew:
                lines += ["", "---", "## Distribution Statistics", "",
                          "Absolute skewness > 1 may benefit from log transformation.",
                          "",
                          "| Feature | Skewness | Direction | Flag |",
                          "|:---|---:|:---|:---:|"]
                for feat, skew in top_skew:
                    direction = "Right-tailed" if skew > 0 else "Left-tailed"
                    flag = "⚠" if abs(skew) > 2 else ""
                    lines.append(f"| `{feat}` | `{skew:+.4f}` | {direction} | {flag} |")

        if "variance_groups" in profile:
            dead = profile["variance_groups"].get("dead_or_constant", [])
            if dead:
                lines += ["", "### Zero-Variance Features",
                          "", "> These carry no information and will be ignored by tree models.",
                          ""]
                lines.append(" &nbsp; ".join(f"`{f}`" for f in dead))

        # ── 6. Pipeline steps ────────────────────────────────────────
        lines += ["", "---", "## Preprocessing Pipeline", ""]
        if pipeline_steps:
            step_desc = {
                "NumericImputer":         "Fills missing values in numeric columns (default: median)",
                "CategoricalImputer":     "Fills missing values in categorical columns (default: most frequent)",
                "OutlierClipper":         "Clips outliers to [Q1 - 1.5×IQR, Q3 + 1.5×IQR]",
                "OneHotEncoderStrategy":  "One-hot encodes low-cardinality categoricals",
                "OrdinalEncoderStrategy": "Ordinal encodes high-cardinality categoricals",
                "StandardScalerStrategy": "Z-score normalisation — zero mean, unit variance",
                "MinMaxScalerStrategy":   "Scales numeric features to [0, 1]",
            }
            lines += ["| Step | Strategy | Description |",
                      "|:---:|:---|:---|"]
            for i, (name, strat) in enumerate(pipeline_steps, 1):
                cls  = type(strat).__name__
                desc = step_desc.get(cls, "Custom transformation step")
                lines.append(f"| {i} | `{cls}` | {desc} |")
        else:
            lines.append("> ℹ Preprocessing was disabled (`preprocess=False`).")

        # ── 7. Saved files ───────────────────────────────────────────
        saved_files = []
        if preprocessed_train is not None:
            p = os.path.join(self._dir, "preprocessed_train.csv")
            preprocessed_train.to_csv(p, index=False)
            saved_files.append(("preprocessed_train.csv",
                                 f"{len(preprocessed_train):,} rows × {len(preprocessed_train.columns)} cols",
                                 "Training set after preprocessing"))
        if preprocessed_test is not None:
            p = os.path.join(self._dir, "preprocessed_test.csv")
            preprocessed_test.to_csv(p, index=False)
            saved_files.append(("preprocessed_test.csv",
                                 f"{len(preprocessed_test):,} rows × {len(preprocessed_test.columns)} cols",
                                 "Test set after preprocessing"))

        if saved_files:
            lines += ["", "---", "## Saved Data Artefacts", "",
                      "| File | Shape | Contents |", "|:---|:---|:---|"]
            for fname, shape, desc in saved_files:
                lines.append(f"| `{fname}` | {shape} | {desc} |")

        self._write("preprocessing_report.md", lines)

    # ─────────────────────────────────────────────────────────────────
    # 2. Model metrics Excel
    # ─────────────────────────────────────────────────────────────────

    def log_model_metrics(self, all_results: List[Dict[str, Any]], task_type: str) -> None:
        rows = []
        for rd in all_results:
            for name, metrics in rd.items():
                rows.append({"Model": name, "Status": "ok", **(metrics or {})}
                            if metrics else {"Model": name, "Status": "failed"})
        df = pd.DataFrame(rows)
        path = os.path.join(self._dir, "model_metrics.xlsx")
        primary = "Accuracy" if task_type == "classification" else "R2"
        try:
            import openpyxl
            from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
            from openpyxl.utils import get_column_letter

            with pd.ExcelWriter(path, engine="openpyxl") as writer:
                df.to_excel(writer, sheet_name="All Models", index=False)
                ok   = df[df["Status"]=="ok"].drop(columns=["Status"])
                fail = df[df["Status"]=="failed"][["Model"]]
                if not ok.empty:
                    if primary in ok.columns:
                        ok = ok.sort_values(primary, ascending=False)
                    ok.to_excel(writer, sheet_name="Ranked", index=False)
                if not fail.empty:
                    fail.to_excel(writer, sheet_name="Failed", index=False)

                hdr_fill  = PatternFill("solid", fgColor="1F3864")
                hdr_font  = Font(color="FFFFFF", bold=True, size=10)
                best_fill = PatternFill("solid", fgColor="C6EFCE")
                best_font = Font(bold=True, color="1A5C2E", size=10)
                thin      = Side(style="thin", color="D9E1EC")
                border    = Border(left=thin, right=thin, top=thin, bottom=thin)

                for ws in writer.sheets.values():
                    # Header row
                    for cell in ws[1]:
                        cell.fill      = hdr_fill
                        cell.font      = hdr_font
                        cell.alignment = Alignment(horizontal="center", vertical="center")
                        cell.border    = border
                    ws.row_dimensions[1].height = 20
                    # Data rows
                    for row in ws.iter_rows(min_row=2):
                        for cell in row:
                            cell.border    = border
                            cell.alignment = Alignment(horizontal="center")
                    # Best row highlight (Ranked sheet only)
                    if ws.title == "Ranked" and ws.max_row > 1:
                        for cell in ws[2]:
                            cell.fill = best_fill
                            cell.font = best_font
                    # Column widths
                    for col in ws.columns:
                        w = max(len(str(c.value or "")) for c in col)
                        ws.column_dimensions[get_column_letter(col[0].column)].width = min(w+4, 38)
                    # Freeze header
                    ws.freeze_panes = "A2"

            print("[MLTuneX] Saved model_metrics.xlsx")
        except ImportError:
            csv_path = os.path.join(self._dir, "model_metrics.csv")
            df.to_csv(csv_path, index=False)
            print("[MLTuneX] openpyxl unavailable - saved model_metrics.csv")

    # ─────────────────────────────────────────────────────────────────
    # 3. Selection report
    # ─────────────────────────────────────────────────────────────────

    def log_selection(
        self,
        all_results_df: pd.DataFrame,
        selected_df: pd.DataFrame,
        selection_strategy: str,
        selector_config: Any,
    ) -> None:
        strategy_meta = {
            "topk": (
                "Top-K by Primary Metric",
                "Ranks all evaluated models by a single metric in descending order. "
                "Straightforward, interpretable, and effective for most use cases.",
            ),
            "stability": (
                "Stability-Aware Selection",
                "Computes a composite score that penalises models with high variance "
                "across all metric dimensions. Favours models that are reliably good "
                "rather than excellent on one metric and poor on others.",
            ),
            "generalization": (
                "Generalisation-Aware Selection",
                "Penalises models with a large gap between train-set and test-set "
                "performance. Selects models that are likely to transfer well to "
                "unseen data rather than those that have overfit the training set.",
            ),
        }
        sname, sdesc = strategy_meta.get(selection_strategy, ("Custom Strategy", ""))
        primary      = getattr(selector_config, "primary_metric", "Accuracy")

        lines = _doc(
            "Model Selection Report",
            f"Strategy: **{sname}**",
            self._ts_human, self._name,
        )

        # ── Strategy card ────────────────────────────────────────────
        lines += [
            "## Selection Strategy", "",
            f"**{sname}**", "",
            f"{sdesc}", "",
            "### Configuration", "",
        ]
        lines += _kv_table([
            ("Strategy",          f"`{selection_strategy}`"),
            ("Primary metric",    f"`{primary}`"),
            ("Stability weight",  f"`{getattr(selector_config, 'stability_weight', '—')}`"),
            ("Train metric",      f"`{getattr(selector_config, 'train_metric', 'n/a')}`"),
            ("Gap penalty",       f"`{getattr(selector_config, 'gap_penalty', '—')}`"),
            ("Top-K requested",   f"`{len(selected_df)}`"),
        ])

        # ── Full leaderboard ─────────────────────────────────────────
        lines += ["", "---", "## Full Model Leaderboard", "",
                  f"> Sorted by **{primary}** descending. "
                  f"{len(all_results_df)} models evaluated in total.", ""]
        if primary in all_results_df.columns:
            all_results_df = all_results_df.sort_values(primary, ascending=False)
        lines += _df_to_md(all_results_df, bold_col=primary)

        # ── Podium ───────────────────────────────────────────────────
        lines += ["", "---", f"## Selected Candidates", "",
                  f"> The following **{len(selected_df)}** model(s) advance to "
                  f"the AI-guided hyperparameter optimisation stage.", ""]
        lines += _df_to_md(selected_df, bold_col=primary)

        # ── Selection summary ────────────────────────────────────────
        top_name = selected_df.iloc[0]["Model"] if len(selected_df) else "—"
        top_score = (
            f"{selected_df.iloc[0][primary]:.4f}"
            if len(selected_df) and primary in selected_df.columns
            else "—"
        )
        lines += ["", "---", "## Summary", ""]
        lines += _kv_table([
            ("Total models evaluated", str(len(all_results_df))),
            ("Candidates selected",    str(len(selected_df))),
            ("Top candidate",          f"`{top_name}`"),
            (f"Top candidate {primary}", f"`{top_score}`"),
        ])

        self._write("selection_report.md", lines)

    # ─────────────────────────────────────────────────────────────────
    # 4. Tuning report
    # ─────────────────────────────────────────────────────────────────

    def log_tuning(
        self,
        ai_suggestions: List[Dict[str, Any]],
        trial_history: List[Dict[str, Any]],
        best_model_name: str,
        best_params: Dict[str, Any],
        best_score: float,
        n_trials: int,
        optimizer_method: str,
    ) -> None:
        lines = _doc(
            "Hyperparameter Tuning Report",
            f"Optimizer: **{optimizer_method}** &nbsp;·&nbsp; Trials: **{n_trials}**",
            self._ts_human, self._name,
        )

        # ── AI search spaces ─────────────────────────────────────────
        lines += ["## AI-Suggested Search Spaces", "",
                  "> The AI advisor analysed dataset characteristics and initial model "
                  "performance to propose targeted hyperparameter ranges for each "
                  "candidate model.", ""]

        for suggestion in ai_suggestions:
            model_name  = suggestion.get("model_name", "unknown")
            hyperparams = suggestion.get("suggested_hyperparameters", {})
            lines += [f"### {model_name}", "",
                      "| Parameter | Type | Range / Values | Scale |",
                      "|:---|:---:|:---|:---:|"]
            for param, defn in hyperparams.items():
                ptype = defn.get("type", "?")
                scale = "log" if defn.get("log") else "—"
                if "values" in defn:
                    rng = " · ".join(f"`{v}`" for v in defn["values"])
                    scale = "—"
                elif "low" in defn and "high" in defn:
                    rng = f"`{defn['low']}` → `{defn['high']}`"
                else:
                    rng = str(defn)
                lines.append(f"| `{param}` | `{ptype}` | {rng} | {scale} |")
            lines.append("")

        # ── Score progression stats ──────────────────────────────────
        if trial_history:
            scores  = [t.get("score", 0) for t in trial_history]
            best_i  = max(range(len(scores)), key=lambda i: scores[i])
            improve = scores[best_i] - scores[0]

            lines += ["---", "## Score Progression", "",
                      "| Metric | Value |", "|:---|---:|",
                      f"| First trial | `{scores[0]:.5f}` |",
                      f"| Best trial  | `{scores[best_i]:.5f}` (trial #{best_i}) |",
                      f"| Last trial  | `{scores[-1]:.5f}` |",
                      f"| Mean        | `{sum(scores)/len(scores):.5f}` |",
                      f"| Std dev     | `{pd.Series(scores).std():.5f}` |",
                      f"| Improvement | `{improve:+.5f}` |",
                      ""]

        # ── Trial history table ──────────────────────────────────────
        sorted_trials = sorted(trial_history, key=lambda t: t.get("score",0), reverse=True)
        shown         = min(25, len(sorted_trials))
        lines += ["---", "## Trial History", "",
                  f"> Top **{shown}** of **{len(trial_history)}** trials shown, "
                  f"sorted by score descending.", "",
                  "| Rank | Trial | Model | Score | Parameters |",
                  "|:---:|:---:|:---|---:|:---|"]
        medals = {1: "🥇", 2: "🥈", 3: "🥉"}
        for rank, t in enumerate(sorted_trials[:shown], 1):
            params_str = json.dumps(t.get("params", {}), default=str)
            if len(params_str) > 80:
                params_str = params_str[:77] + "..."
            label = medals.get(rank, str(rank))
            lines.append(
                f"| {label} | {t.get('trial','?')} "
                f"| `{t.get('model','?')}` "
                f"| **{t.get('score',0):.5f}** "
                f"| `{params_str}` |"
            )

        # ── Best configuration ───────────────────────────────────────
        lines += ["", "---", "## Best Configuration", ""]
        lines += _kv_table([
            ("Model",      f"`{best_model_name}`"),
            ("CV Score",   f"`{best_score:.6f}`"),
            ("Trials run", f"`{len(trial_history)}`"),
        ])
        lines += ["", "### Optimal Hyperparameters", ""]
        lines += _kv_table([(f"`{k}`", f"`{v}`") for k, v in best_params.items()])
        lines += [
            "",
            "---",
            "",
            "> **Next step:** use `joblib.load('models/preprocessing_pipeline.joblib')` "
            "to transform new data, then `joblib.load('models/" + best_model_name + ".joblib')` "
            "to generate predictions.",
        ]

        self._write("tuning_report.md", lines)

    # ─────────────────────────────────────────────────────────────────
    # Private
    # ─────────────────────────────────────────────────────────────────

    def _write(self, filename: str, lines: List[str]) -> None:
        path = os.path.join(self._dir, filename)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(_GEN_COMMENT + "\n")
            fh.write("\n".join(lines) + "\n")
        print(f"[MLTuneX] Saved {filename}")

    @property
    def experiment_dir(self) -> str:
        return self._dir