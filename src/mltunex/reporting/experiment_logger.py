"""
mltunex.reporting.experiment_logger
─────────────────────────────────────
Produces four richly-formatted experiment artefacts per run:

  1. preprocessing_report.md   — data profile, pipeline steps, modified data CSVs
  2. model_metrics.xlsx        — per-model metrics, ranked & failed sheets
  3. selection_report.md       — selector config, full results, chosen candidates
  4. tuning_report.md          — AI search spaces, trial history, best config
"""

from __future__ import annotations

import json
import os
from datetime import datetime
from typing import Any, Dict, List, Optional, Tuple

import pandas as pd

_BADGE = "<!-- generated by MLTuneX -->"
_LOGO  = "🤖 **MLTuneX**"


def _header(title: str, timestamp: str, subtitle: str = "") -> List[str]:
    """Produce a consistent document header block."""
    lines = [
        f"# {_LOGO} — {title}",
        "",
        f"> Generated by **MLTuneX Automated ML Pipeline**  ",
        f"> Experiment timestamp: `{timestamp}`" + (f"  \n> {subtitle}" if subtitle else ""),
        "",
        "---",
        "",
    ]
    return lines


class ExperimentLogger:
    """
    Writes all experiment artefacts for a single MLTuneX run.

    Parameters
    ----------
    base_log_dir : str
        Root directory under which the timestamped experiment folder is created.
    experiment_name : str, optional
        Human-readable tag prepended to the folder name.
    """

    def __init__(self, base_log_dir: str = "logs/", experiment_name: str = "exp") -> None:
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        self._dir = os.path.join(base_log_dir, f"{experiment_name}_{timestamp}")
        os.makedirs(self._dir, exist_ok=True)
        self._timestamp = timestamp
        self._exp_name  = experiment_name
        print(f"[MLTuneX] Experiment artefacts -> {self._dir}")

    # ──────────────────────────────────────────────────────────────────
    # 1. Preprocessing report
    # ──────────────────────────────────────────────────────────────────

    def log_preprocessing(
        self,
        profile: Dict[str, Any],
        pipeline_steps: List[Tuple[str, Any]],
        profiling_strategy: str,
        preprocessed_train: Optional[pd.DataFrame] = None,
        preprocessed_test:  Optional[pd.DataFrame] = None,
    ) -> None:
        lines: List[str] = _header(
            "Data Preprocessing Report",
            self._timestamp,
            f"Profiling strategy: `{profiling_strategy}`",
        )

        # ── Overview cards ────────────────────────────────────────────
        lines += [
            "## 📊 Dataset Overview",
            "",
            "| Property | Value |",
            "|:---|:---:|",
        ]
        for key in ("num_rows", "num_features", "target_column", "imbalance_ratio"):
            val = profile.get(key, "—")
            icon = {"num_rows": "🗂", "num_features": "🔢",
                    "target_column": "🎯", "imbalance_ratio": "⚖️"}.get(key, "•")
            lines.append(f"| {icon} **{key.replace('_', ' ').title()}** | `{val}` |")

        # ── Target distribution ───────────────────────────────────────
        target_dist = profile.get("target_distribution", {})
        if target_dist:
            lines += ["", "### 🎯 Target Distribution", "",
                      "| Class | Proportion |", "|:---|---:|"]
            for cls, pct in list(target_dist.items())[:15]:
                bar = "█" * int(pct * 20)
                lines.append(f"| `{cls}` | {pct:.2%} {bar} |")

        # ── Missing data ──────────────────────────────────────────────
        lines += ["", "---", "## 🔍 Missing Data Analysis", ""]
        missing_counts = profile.get("missing_counts", {})
        missing_cols   = {k: v for k, v in missing_counts.items() if v > 0}
        if missing_cols:
            lines += ["| Column | Count | Percentage | Severity |",
                      "|:---|---:|---:|:---:|"]
            pct_map = profile.get("missing_pct", {})
            for col, count in missing_cols.items():
                pct = pct_map.get(col, 0)
                sev = "🔴 High" if pct > 30 else ("🟡 Medium" if pct > 5 else "🟢 Low")
                lines.append(f"| `{col}` | {count} | {pct}% | {sev} |")
        else:
            lines.append("> ✅ **No missing values detected** in the dataset.")

        # ── Feature types ─────────────────────────────────────────────
        num_feats = profile.get("numeric_features", [])
        cat_feats = profile.get("categorical_features", [])
        lines += [
            "", "---", "## 🧩 Feature Types", "",
            f"### 🔢 Numeric Features ({len(num_feats)})",
            "",
        ]
        if num_feats:
            for i in range(0, len(num_feats), 5):
                chunk = num_feats[i:i+5]
                lines.append("  ".join(f"`{f}`" for f in chunk))
        else:
            lines.append("_None_")

        lines += [f"", f"### 🔤 Categorical Features ({len(cat_feats)})", ""]
        if cat_feats:
            for i in range(0, len(cat_feats), 5):
                chunk = cat_feats[i:i+5]
                lines.append("  ".join(f"`{f}`" for f in chunk))
        else:
            lines.append("_None_")

        # ── Distribution statistics (extended) ────────────────────────
        if "skewness" in profile:
            top_skewed = sorted(
                profile["skewness"].items(), key=lambda x: abs(x[1]), reverse=True
            )[:10]
            lines += [
                "", "---", "## 📈 Distribution Statistics", "",
                "### Top Skewed Features",
                "> Features with |skew| > 1 may benefit from log-transformation.",
                "",
                "| # | Feature | Skewness | Shape |",
                "|:---:|:---|---:|:---|",
            ]
            for rank, (feat, skew) in enumerate(top_skewed, 1):
                shape = "↗ Right-skewed" if skew > 0 else "↙ Left-skewed"
                flag  = " ⚠️" if abs(skew) > 2 else ""
                lines.append(f"| {rank} | `{feat}` | {skew:+.4f}{flag} | {shape} |")

        if "variance_groups" in profile:
            vg = profile["variance_groups"]
            dead = vg.get("dead_or_constant", [])
            if dead:
                lines += [
                    "", "### ⚠️ Constant / Near-Constant Features",
                    "",
                    "> These features carry no information and should be dropped.",
                    "",
                ]
                lines.append("  ".join(f"`{f}`" for f in dead))

        # ── Pipeline steps ────────────────────────────────────────────
        lines += ["", "---", "## ⚙️ Preprocessing Pipeline", ""]
        if pipeline_steps:
            lines += [
                "| # | Step Name | Strategy Class | Description |",
                "|:---:|:---|:---|:---|",
            ]
            step_descriptions = {
                "NumericImputer":        "Fills missing numeric values",
                "CategoricalImputer":    "Fills missing categorical values",
                "OutlierClipper":        "Clips numeric outliers via IQR",
                "OneHotEncoderStrategy": "One-hot encodes low-cardinality categoricals",
                "OrdinalEncoderStrategy":"Ordinal encodes high-cardinality categoricals",
                "StandardScalerStrategy":"Z-score normalisation of numeric features",
                "MinMaxScalerStrategy":  "Min-max scaling of numeric features to [0,1]",
            }
            for idx, (step_name, strategy) in enumerate(pipeline_steps, 1):
                cls  = type(strategy).__name__
                desc = step_descriptions.get(cls, "—")
                lines.append(f"| {idx} | `{step_name}` | `{cls}` | {desc} |")
        else:
            lines.append("> ℹ️ No preprocessing was applied (`preprocess=False`).")

        # ── Data artefacts note ───────────────────────────────────────
        if preprocessed_train is not None or preprocessed_test is not None:
            lines += [
                "", "---", "## 💾 Saved Data Artefacts", "",
                "| File | Rows | Columns |",
                "|:---|---:|---:|",
            ]
        if preprocessed_train is not None:
            path = os.path.join(self._dir, "preprocessed_train.csv")
            preprocessed_train.to_csv(path, index=False)
            lines.append(
                f"| `preprocessed_train.csv` | {len(preprocessed_train)} "
                f"| {len(preprocessed_train.columns)} |"
            )
        if preprocessed_test is not None:
            path = os.path.join(self._dir, "preprocessed_test.csv")
            preprocessed_test.to_csv(path, index=False)
            lines.append(
                f"| `preprocessed_test.csv` | {len(preprocessed_test)} "
                f"| {len(preprocessed_test.columns)} |"
            )

        self._write_md("preprocessing_report.md", lines)

    # ──────────────────────────────────────────────────────────────────
    # 2. Model metrics Excel
    # ──────────────────────────────────────────────────────────────────

    def log_model_metrics(self, all_results: List[Dict[str, Any]], task_type: str) -> None:
        rows = []
        for result_dict in all_results:
            for model_name, metrics in result_dict.items():
                if metrics is None:
                    rows.append({"Model": model_name, "Status": "failed"})
                else:
                    rows.append({"Model": model_name, "Status": "ok", **metrics})

        df = pd.DataFrame(rows)
        path = os.path.join(self._dir, "model_metrics.xlsx")

        try:
            import openpyxl
            from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
            from openpyxl.utils import get_column_letter

            with pd.ExcelWriter(path, engine="openpyxl") as writer:
                df.to_excel(writer, sheet_name="All Models", index=False)

                ok_df   = df[df["Status"] == "ok"].drop(columns=["Status"])
                fail_df = df[df["Status"] == "failed"][["Model"]]
                primary = "Accuracy" if task_type == "classification" else "R2"

                if not ok_df.empty:
                    if primary in ok_df.columns:
                        ok_df = ok_df.sort_values(primary, ascending=False)
                    ok_df.to_excel(writer, sheet_name="Ranked", index=False)
                if not fail_df.empty:
                    fail_df.to_excel(writer, sheet_name="Failed", index=False)

                # Styling
                header_fill  = PatternFill("solid", fgColor="1F3864")
                header_font  = Font(color="FFFFFF", bold=True)
                best_fill    = PatternFill("solid", fgColor="C6EFCE")
                border_side  = Side(style="thin", color="CCCCCC")
                cell_border  = Border(left=border_side, right=border_side,
                                      top=border_side, bottom=border_side)

                for sheet_name, ws in writer.sheets.items():
                    # Header row styling
                    for cell in ws[1]:
                        cell.fill      = header_fill
                        cell.font      = header_font
                        cell.alignment = Alignment(horizontal="center")
                        cell.border    = cell_border

                    # Auto-size + highlight best row in Ranked sheet
                    for col_idx, col in enumerate(ws.columns, 1):
                        max_len = max((len(str(c.value or "")) for c in col), default=8)
                        ws.column_dimensions[get_column_letter(col_idx)].width = min(max_len + 4, 40)
                        for cell in col[1:]:
                            cell.border = cell_border

                    if sheet_name == "Ranked" and ws.max_row > 1:
                        for cell in ws[2]:  # top-ranked row
                            cell.fill = best_fill
                            cell.font = Font(bold=True)

            print("[MLTuneX] Saved model_metrics.xlsx")
        except ImportError:
            csv_path = os.path.join(self._dir, "model_metrics.csv")
            df.to_csv(csv_path, index=False)
            print("[MLTuneX] openpyxl unavailable - saved model_metrics.csv")

    # ──────────────────────────────────────────────────────────────────
    # 3. Selection report
    # ──────────────────────────────────────────────────────────────────

    def log_selection(
        self,
        all_results_df: pd.DataFrame,
        selected_df: pd.DataFrame,
        selection_strategy: str,
        selector_config: Any,
    ) -> None:
        strategy_meta = {
            "topk": ("🏆 Top-K by Primary Metric",
                     "Ranks models by a single metric in descending order. "
                     "Simple, fast, and interpretable."),
            "stability": ("⚖️ Stability-Aware Selection",
                          "Penalises models with high variance across metrics. "
                          "Favours consistent, reliable performance over peak scores."),
            "generalization": ("🎯 Generalisation-Aware Selection",
                               "Penalises large train/test metric gaps. "
                               "Prefers models that don't overfit."),
        }
        icon, desc = strategy_meta.get(selection_strategy, ("🔧 Custom", "Custom strategy."))

        lines: List[str] = _header(
            "Model Selection Report",
            self._timestamp,
            f"Strategy: {icon}",
        )

        lines += [
            f"## {icon} Selection Strategy",
            "",
            f"> {desc}",
            "",
            "### Configuration",
            "",
            "| Parameter | Value | Purpose |",
            "|:---|:---:|:---|",
        ]
        param_docs = {
            "primary_metric":   "Main metric used for ranking",
            "stability_weight": "Penalty weight for cross-metric variance (StabilityAware only)",
            "train_metric":     "Train-set metric column name (Generalization only)",
            "gap_penalty":      "Penalty weight for train/test gap (Generalization only)",
        }
        for attr, purpose in param_docs.items():
            val = getattr(selector_config, attr, "—")
            lines.append(f"| `{attr}` | `{val}` | {purpose} |")

        # ── Full leaderboard ──────────────────────────────────────────
        lines += ["", "---", "## 📋 Full Model Leaderboard", ""]
        primary = getattr(selector_config, "primary_metric", "Accuracy")
        if primary in all_results_df.columns:
            all_results_df = all_results_df.sort_values(primary, ascending=False)

        lines += self._df_to_md(all_results_df, highlight_col=primary)

        # ── Selected candidates ───────────────────────────────────────
        lines += [
            "", "---",
            f"## ✅ Selected Top-{len(selected_df)} Candidates",
            "",
            f"> These models advance to the AI-guided hyperparameter optimisation stage.",
            "",
        ]
        lines += self._df_to_md(selected_df, highlight_col=primary)

        lines += [
            "", "---",
            f"## ℹ️ Selection Summary",
            "",
            f"- **Strategy used:** `{selection_strategy}`",
            f"- **Primary ranking metric:** `{primary}`",
            f"- **Total models evaluated:** {len(all_results_df)}",
            f"- **Candidates selected:** {len(selected_df)}",
            f"- **Top candidate:** `{selected_df.iloc[0]['Model'] if len(selected_df) else '—'}`",
        ]

        self._write_md("selection_report.md", lines)

    # ──────────────────────────────────────────────────────────────────
    # 4. Tuning report
    # ──────────────────────────────────────────────────────────────────

    def log_tuning(
        self,
        ai_suggestions: List[Dict[str, Any]],
        trial_history: List[Dict[str, Any]],
        best_model_name: str,
        best_params: Dict[str, Any],
        best_score: float,
        n_trials: int,
        optimizer_method: str,
    ) -> None:
        lines: List[str] = _header(
            "Hyperparameter Tuning Report",
            self._timestamp,
            f"Optimizer: `{optimizer_method}` · Trials: `{n_trials}`",
        )

        # ── AI suggestions ────────────────────────────────────────────
        lines += [
            "## 🤖 AI-Suggested Hyperparameter Search Spaces",
            "",
            "> The following search spaces were proposed by the AI advisor "
            "based on dataset characteristics and initial model performance.",
            "",
        ]

        for suggestion in ai_suggestions:
            model_name  = suggestion.get("model_name", "unknown")
            hyperparams = suggestion.get("suggested_hyperparameters", {})
            lines += [
                f"### 🔧 {model_name}",
                "",
                "| Parameter | Type | Search Range / Values | Scale |",
                "|:---|:---:|:---|:---:|",
            ]
            for param, defn in hyperparams.items():
                ptype = defn.get("type", "?")
                scale = "log" if defn.get("log") else "linear"
                if "values" in defn:
                    rng   = str(defn["values"])
                    scale = "—"
                elif "low" in defn and "high" in defn:
                    rng = f"`{defn['low']}` → `{defn['high']}`"
                else:
                    rng = str(defn)
                lines.append(f"| `{param}` | `{ptype}` | {rng} | {scale} |")
            lines.append("")

        # ── Trial history ─────────────────────────────────────────────
        sorted_trials = sorted(trial_history, key=lambda t: t.get("score", 0), reverse=True)
        shown = min(20, len(sorted_trials))

        lines += [
            "---",
            "## 📊 Trial History",
            "",
            f"> Showing top **{shown}** of **{len(trial_history)}** trials "
            f"(sorted by score ↓).",
            "",
            "| Rank | Trial | Model | Score | Key Parameters |",
            "|:---:|:---:|:---|---:|:---|",
        ]

        for rank, t in enumerate(sorted_trials[:shown], 1):
            params_str = json.dumps(t.get("params", {}), default=str)
            if len(params_str) > 90:
                params_str = params_str[:87] + "…"
            medal = {1: "🥇", 2: "🥈", 3: "🥉"}.get(rank, f"{rank}.")
            lines.append(
                f"| {medal} | {t.get('trial', '?')} "
                f"| {t.get('model', '?')} "
                f"| **{t.get('score', 0):.5f}** "
                f"| `{params_str}` |"
            )

        # Score progression summary
        if trial_history:
            scores   = [t.get("score", 0) for t in trial_history]
            best_at  = max(range(len(scores)), key=lambda i: scores[i])
            lines += [
                "",
                "### 📈 Score Progression",
                "",
                f"| Metric | Value |",
                "|:---|---:|",
                f"| First trial score  | `{scores[0]:.5f}` |",
                f"| Best trial score   | `{max(scores):.5f}` (trial #{best_at})  |",
                f"| Last trial score   | `{scores[-1]:.5f}` |",
                f"| Mean score         | `{sum(scores)/len(scores):.5f}` |",
                f"| Improvement        | `{max(scores) - scores[0]:+.5f}` |",
            ]

        # ── Best config ───────────────────────────────────────────────
        lines += [
            "",
            "---",
            "## 🏆 Final Best Configuration",
            "",
            f"| Property | Value |",
            "|:---|:---|",
            f"| **Best Model** | `{best_model_name}` |",
            f"| **Best CV Score** | `{best_score:.6f}` |",
            f"| **Total Trials** | `{len(trial_history)}` |",
            "",
            "### ⚙️ Optimal Hyperparameters",
            "",
            "| Parameter | Optimal Value |",
            "|:---|:---|",
        ]
        for param, value in best_params.items():
            lines.append(f"| `{param}` | `{value}` |")

        lines += [
            "",
            "---",
            f"> 💡 **Tip:** Use these hyperparameters as a starting point for "
            f"further manual fine-tuning.",
        ]

        self._write_md("tuning_report.md", lines)

    # ──────────────────────────────────────────────────────────────────
    # Private helpers
    # ──────────────────────────────────────────────────────────────────

    def _write_md(self, filename: str, lines: List[str]) -> None:
        path = os.path.join(self._dir, filename)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(_BADGE + "\n")
            fh.write("\n".join(lines) + "\n")
        print(f"[MLTuneX] Saved {filename}")

    @staticmethod
    def _df_to_md(
        df: pd.DataFrame,
        highlight_col: Optional[str] = None,
    ) -> List[str]:
        """Convert DataFrame to GFM table; optionally bold the highlight column header."""
        if df.empty:
            return ["> _No data available._"]
        cols   = list(df.columns)
        header = "| " + " | ".join(
            f"**{c}**" if c == highlight_col else str(c) for c in cols
        ) + " |"
        sep    = "| " + " | ".join("---" for _ in cols) + " |"
        rows   = []
        for row in df.itertuples(index=False, name=None):
            cells = []
            for val in row:
                cells.append(f"{val:.4f}" if isinstance(val, float) else str(val))
            rows.append("| " + " | ".join(cells) + " |")
        return [header, sep] + rows

    @property
    def experiment_dir(self) -> str:
        return self._dir
